# ---------- Excel：2025 年一季度销售数据 ----------
random.seed(42)
products = {"智能音箱 X1": 299, "无线耳机 Pro": 699, "智能手表 S3": 1299, "扫地机器人 R5": 2499}
sellers = {"张伟": "华东", "李娜": "华南", "王强": "华北", "刘洋": "华东", "陈静": "西南"}
wb = Workbook()
wb.remove(wb.active)
totals = {}  # (区域, 月) -> 金额
qty_by_product = {p: 0 for p in products}
for month in (1, 2, 3):
    ws = wb.create_sheet(f"{month}月明细")
    ws.append(["日期", "订单号", "销售员", "区域", "产品", "数量", "单价（元）", "金额（元）"])
    for k in range(30):
        day = random.randint(1, 28)
        s = random.choice(list(sellers))
        p = random.choice(list(products))
        q = random.randint(1, 20)
        amt = q * products[p]
        ws.append([f"2025-{month:02d}-{day:02d}", f"SO2025{month:02d}{k+1:03d}", s, sellers[s], p, q, products[p], amt])
        totals[(sellers[s], month)] = totals.get((sellers[s], month), 0) + amt
        qty_by_product[p] += q
ws = wb.create_sheet("季度汇总")
ws.append(["区域", "1月销售额（元）", "2月销售额（元）", "3月销售额（元）", "一季度合计（元）"])
for region in ["华东", "华南", "华北", "西南"]:
    vals = [totals.get((region, m), 0) for m in (1, 2, 3)]
    ws.append([region] + vals + [sum(vals)])
ws = wb.create_sheet("销售员信息")
ws.append(["姓名", "负责区域", "入职日期", "提成比例", "联系电话"])
for (n, r), date, rate, tel in zip(sellers.items(), ["2021-06-01", "2022-03-15", "2020-09-01", "2023-07-10", "2024-02-20"],
                                    ["4%", "5%", "4.5%", "3.5%", "3%"], ["138-0000-1001", "138-0000-1002", "138-0000-1003", "138-0000-1004", "138-0000-1005"]):
    ws.append([n, r, date, rate, tel])
wb.save("sales_2025Q1.xlsx")

# 打印标准答案，方便写测试题
print("区域×月份销售额:", totals)
print("各产品一季度总销量:", qty_by_product)
